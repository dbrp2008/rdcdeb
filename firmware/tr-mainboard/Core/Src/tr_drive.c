#define TR_LINE_MAX 20U
#define TR_RX_QUEUE_LEN 8U
#define TR_MOTION_AVG_SAMPLES 3U
#define TR_CAN_FEEDBACK_TIMEOUT_MS 100U
#define RM_GEAR_RATIO TR_MOTOR_GEAR_RATIO /* M3508 P19: rotor rpm = wheel rpm * 19.2 */

#if TR_BACK_ON_CAN2
extern CAN_HandleTypeDef hcan2; /* generated by CubeMX when CAN2 is enabled; rm_motor.c supplies a placeholder otherwise */
#define BACK_BUS (&hcan2)
#else
#define BACK_BUS (&hcan1)
#endif

/* The bus each wheel's ESC is on. */
static CAN_HandleTypeDef *wheel_bus(int wheel_index) { return (wheel_index == TR_WHEEL_B) ? BACK_BUS : &hcan1; }

/* ESC ID (blink count set with the SET button) for each wheel, in the order FL, FR, B.
 * Blink 1 = left (front-left) wheel, blink 2 = right (front-right) wheel, blink 3 = back wheel. */
static const RM_Motor wheel_motor[TR_WHEEL_COUNT] = {RM_MOTOR_1, RM_MOTOR_2, RM_MOTOR_3};
static const float wheel_sign[TR_WHEEL_COUNT] = {TR_FL_SIGN, TR_FR_SIGN, TR_B_SIGN};

/* Wheel drive direction (unit vector) for wheels at 150, 30 and 270 degrees
 * around the robot (x = right, y = forward):  t = (-sin(phi), cos(phi)). */
static const float wheel_tx[TR_WHEEL_COUNT] = {-0.5f, -0.5f, 1.0f};
static const float wheel_ty[TR_WHEEL_COUNT] = {-0.8660254f, 0.8660254f, 0.0f};

/* ---- UART line receive queue (byte framing in the ISR, parse in the main loop) ---- */
static uint8_t rx_byte;
static char rx_line_buf[TR_LINE_MAX];
static uint8_t rx_line_len = 0U;
static bool rx_line_overflow = false;
static bool rx_line_discard = false;
static char rx_line_queue[TR_RX_QUEUE_LEN][TR_LINE_MAX];
static uint8_t rx_line_queue_len[TR_RX_QUEUE_LEN];
static volatile uint8_t rx_queue_head = 0U, rx_queue_tail = 0U;

/* Latest commands. Movement ratios are in hundredths (-100..100). Each kind has its own timestamp so a stale one
 * is dropped by itself (e.g. the stick lines stop but the mechanism line keeps arriving). These are main-loop only. */
static int16_t cmd_mx = 0, cmd_my = 0, cmd_rot = 0;
static int16_t move_history[TR_MOTION_AVG_SAMPLES][2];
static int16_t rotation_history[TR_MOTION_AVG_SAMPLES];
static uint8_t move_history_count = 0U, move_history_next = 0U;
static uint8_t rotation_history_count = 0U, rotation_history_next = 0U;
static int8_t cmd_mech = 0; /* +1 = GC close (toward GRIP), -1 = GO open (toward OUT), 0 = GS stop */
static uint32_t last_m_tick = 0, last_r_tick = 0, last_g_tick = 0, last_packet_tick = 0;
static bool m_seen = false, r_seen = false, g_seen = false, packet_seen = false;
static bool heading_requested, heading_zero_requested, heading_command_seen;
static bool heading_transition_pending;
static uint32_t last_heading_tick;
static TRHeading heading;
static TRTurn turn;
static RdcMessageType last_turn_command = RDC_MESSAGE_TURN_CANCEL;
static RdcMessageType turn_request = RDC_MESSAGE_NONE;
static bool turn_seen, turn_cancel_requested;
static uint32_t last_turn_tick;

/* ---- Receive diagnostics (shown on the TFT) ---- */
static volatile uint32_t dbg_rx_bytes = 0;  /* every byte that arrived on USART1 */
static volatile uint32_t dbg_pkt_ok = 0;    /* valid command lines */
static volatile uint32_t dbg_pkt_bad = 0;   /* malformed or dropped command lines */
static volatile uint32_t dbg_uart_err = 0;  /* UART hardware errors (framing/noise/overrun, usually wrong baud) */
static uint32_t dbg_ack_tx_err = 0U;        /* ACK transmit failures; main-loop only */
static uint16_t ack_sequence = 0U;
static uint16_t pending_ack_count = 0U; /* main-loop ACK backlog */

/* ---- Control side (main loop only) ---- */
typedef struct {
  float setpoint_rotor_rpm; /* requested target */
  float integ_a;            /* PID integral term, in amps */
  float prev_meas_rpm;
  float current_a;          /* last command */
} Wheel;

static Wheel wheel[TR_WHEEL_COUNT];
static uint32_t last_ctrl_tick = 0;
static TRDrive_Status status = {0};

/* Average continuous motion inputs independently; mechanism commands stay discrete. */
static void reset_move_average(void)
{
  memset(move_history, 0, sizeof(move_history));
  move_history_count = 0U;
  move_history_next = 0U;
  cmd_mx = 0;
  cmd_my = 0;
}

static void reset_rotation_average(void)
{
  memset(rotation_history, 0, sizeof(rotation_history));
  rotation_history_count = 0U;
  rotation_history_next = 0U;
  cmd_rot = 0;
}

static void add_move_sample(int16_t x, int16_t y)
{
  move_history[move_history_next][0] = x;
  move_history[move_history_next][1] = y;
  move_history_next = (uint8_t)((move_history_next + 1U) % TR_MOTION_AVG_SAMPLES);
  if (move_history_count < TR_MOTION_AVG_SAMPLES) ++move_history_count;

  int32_t sum_x = 0, sum_y = 0;
  for (uint8_t i = 0U; i < move_history_count; ++i) {
    sum_x += move_history[i][0];
    sum_y += move_history[i][1];
  }
  cmd_mx = (int16_t)(sum_x / (int32_t)move_history_count);
  cmd_my = (int16_t)(sum_y / (int32_t)move_history_count);
}

static void add_rotation_sample(int16_t z)
{
  rotation_history[rotation_history_next] = z;
  rotation_history_next = (uint8_t)((rotation_history_next + 1U) % TR_MOTION_AVG_SAMPLES);
  if (rotation_history_count < TR_MOTION_AVG_SAMPLES) ++rotation_history_count;

  int32_t sum = 0;
  for (uint8_t i = 0U; i < rotation_history_count; ++i) sum += rotation_history[i];
  cmd_rot = (int16_t)(sum / (int32_t)rotation_history_count);
}

/* Parse and apply one complete LF-terminated command in foreground context. */
static bool parse_line(const char *line, uint8_t length)
{
  RdcMessage message = {0};
  if (!rdc_parse_line(line, (size_t)length, &message)) {
    return false;
  }

  const uint32_t now = HAL_GetTick();
  switch (message.type) {
    case RDC_MESSAGE_MOVE:
      if (m_seen && ((now - last_m_tick) > TR_LINK_TIMEOUT_MS)) reset_move_average();
      /* Preserve the received movement signs, matching Deb's mainboard. */
      add_move_sample(message.ratio_x_centi, message.ratio_y_centi);
      last_m_tick = now;
      m_seen = true;
      break;
    case RDC_MESSAGE_ROTATE:
      if (r_seen && ((now - last_r_tick) > TR_LINK_TIMEOUT_MS)) reset_rotation_average();
      add_rotation_sample((int16_t)-message.ratio_z_centi); /* reverse Controller R commands only */
      last_r_tick = now;
      r_seen = true;
      break;
    case RDC_MESSAGE_MECHANISM_OPEN:
      cmd_mech = -1;
      last_g_tick = now;
      g_seen = true;
      break;
    case RDC_MESSAGE_MECHANISM_CLOSE:
      cmd_mech = 1;
      last_g_tick = now;
      g_seen = true;
      break;
    case RDC_MESSAGE_MECHANISM_STOP:
      cmd_mech = 0;
      last_g_tick = now;
      g_seen = true;
      break;
    case RDC_MESSAGE_HEADING_OFF:
    case RDC_MESSAGE_HEADING_ON: {
      const bool new_heading_mode = message.type == RDC_MESSAGE_HEADING_ON;
      if (new_heading_mode != heading_requested) heading_transition_pending = true;
      heading_requested = new_heading_mode;
      last_heading_tick = now;
      heading_command_seen = true;
      break;
    }
    case RDC_MESSAGE_HEADING_ZERO:
      heading_zero_requested = true;
      break;
    case RDC_MESSAGE_TURN_IDLE:
    case RDC_MESSAGE_TURN_LEFT:
    case RDC_MESSAGE_TURN_RIGHT:
    case RDC_MESSAGE_TURN_HALF:
    case RDC_MESSAGE_TURN_CANCEL:
      if (message.type == RDC_MESSAGE_TURN_CANCEL) {
        turn_cancel_requested = true;
        turn_request = RDC_MESSAGE_NONE;
      } else if (message.type != RDC_MESSAGE_TURN_IDLE &&
                 last_turn_command == RDC_MESSAGE_TURN_IDLE) {
        turn_request = message.type; /* one request per Y0 -> YL/YR/YU edge */
      }
      last_turn_command = message.type;
      last_turn_tick = now;
      turn_seen = true;
      break;
    default:
      return false; /* ACKs or unsupported message types are not Controller commands. */
  }

  last_packet_tick = now;
  packet_seen = true;
  return true;
}

static bool rx_queue_get_line(char *out, uint8_t *length)
{
  bool available = false;
  __disable_irq();
  if (rx_queue_tail != rx_queue_head) {
    const uint8_t tail = rx_queue_tail;
    *length = rx_line_queue_len[tail];
    memcpy(out, rx_line_queue[tail], *length);
    rx_queue_tail = (uint8_t)((tail + 1U) % TR_RX_QUEUE_LEN);
    available = true;
  }
  __enable_irq();
  return available;
}

static void send_ack(void)
{
  char frame[RDC_PROTOCOL_MAX_FRAME];
  const size_t length = rdc_encode_ack(frame, sizeof(frame), ack_sequence++, 0U);
  if ((length == 0U) ||
      (HAL_UART_Transmit(&huart1, (uint8_t *)frame, (uint16_t)length, 5U) != HAL_OK)) {
    ++dbg_ack_tx_err;
  }
}

static void process_rx_lines(void)
{
  char line[TR_LINE_MAX];
  uint8_t length = 0U;
  while (rx_queue_get_line(line, &length)) {
    if (parse_line(line, length)) {
      ++dbg_pkt_ok;
      if (pending_ack_count < 65535U) {
        ++pending_ack_count;
      }
    } else {
      ++dbg_pkt_bad;
    }
  }
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart != &huart1) {
    return;
  }

  const char c = (char)rx_byte;
  ++dbg_rx_bytes;
  if (c == '\n') {
    if (rx_line_overflow || rx_line_discard) {
      ++dbg_pkt_bad;
    } else if (rx_line_len > 0U) {
      const uint8_t next = (uint8_t)((rx_queue_head + 1U) % TR_RX_QUEUE_LEN);
      if (next != rx_queue_tail) {
        memcpy(rx_line_queue[rx_queue_head], rx_line_buf, rx_line_len);
        rx_line_queue[rx_queue_head][rx_line_len] = '\n';
        rx_line_queue_len[rx_queue_head] = (uint8_t)(rx_line_len + 1U);
        rx_queue_head = next;
      } else {
        ++dbg_pkt_bad; /* queue full: drop this line; the Controller will see a missing ACK */
      }
    }
    rx_line_len = 0U;
    rx_line_overflow = false;
    rx_line_discard = false;
  } else if (c == '\r') {
    rx_line_discard = true; /* protocol requires LF only; reject CRLF */
  } else if (!rx_line_discard) {
    if (rx_line_len < (TR_LINE_MAX - 1U)) {
      rx_line_buf[rx_line_len++] = c;
    } else {
      rx_line_overflow = true;
    }
  }

  (void)HAL_UART_Receive_IT(&huart1, &rx_byte, 1U);
}

/* After a UART error (overrun, noise) make sure reception keeps running. */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart != &huart1) {
    return;
  }
  ++dbg_uart_err;
  rx_line_len = 0U;
  rx_line_overflow = false;
  rx_line_discard = true; /* discard until the next LF to resynchronise */
  (void)HAL_UART_Receive_IT(&huart1, &rx_byte, 1U);
}

void TRDrive_Init(void) {
  reset_move_average();
  reset_rotation_average();
  cmd_mech = 0;
  last_m_tick = last_r_tick = last_g_tick = last_packet_tick = 0U;
  m_seen = r_seen = g_seen = packet_seen = false;
  heading_requested = heading_zero_requested = heading_command_seen = false;
  heading_transition_pending = false;
  last_heading_tick = 0U;
  heading.degrees = 0.0f;
  heading.valid = false;
  memset(&turn, 0, sizeof(turn));
  last_turn_command = RDC_MESSAGE_TURN_CANCEL; /* require Y0 before a turn */
  turn_request = RDC_MESSAGE_NONE;
  turn_seen = turn_cancel_requested = false;
  last_turn_tick = 0U;

  for (int i = 0; i < TR_WHEEL_COUNT; i++) {
    wheel[i].setpoint_rotor_rpm = 0.0f;
    wheel[i].integ_a = 0.0f;
    wheel[i].prev_meas_rpm = 0.0f;
    wheel[i].current_a = 0.0f;
  }
  last_ctrl_tick = HAL_GetTick();

  status.can1_init_ok = (rm_can_init(&hcan1) == HAL_OK) ? 1U : 0U;
#if TR_BACK_ON_CAN2
  status.can2_init_ok = (rm_can_init(&hcan2) == HAL_OK) ? 1U : 0U;
#else
  status.can2_init_ok = 0U;
#endif
  status.can1_tx_ok = 0U;
  status.can2_tx_ok = 0U;
  status.can1_tx_failures = 0U;
  status.can2_tx_failures = 0U;
  TRArm_Init();
  HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
}

static float clampf(float v, float lo, float hi) {
  if (v > hi) return hi;
  if (v < lo) return lo;
  return v;
}

/* Two connected line segments give finer speed control near joystick centre. */
static float shape_stick_magnitude(float magnitude) {
  magnitude = clampf(magnitude, 0.0f, 1.0f);
  if (magnitude <= TR_STICK_CURVE_BREAKPOINT) {
    return magnitude * TR_STICK_CURVE_INNER_OUTPUT / TR_STICK_CURVE_BREAKPOINT;
  }
  return TR_STICK_CURVE_INNER_OUTPUT +
         (magnitude - TR_STICK_CURVE_BREAKPOINT) *
             (1.0f - TR_STICK_CURVE_INNER_OUTPUT) /
             (1.0f - TR_STICK_CURVE_BREAKPOINT);
}

static float shape_stick_axis(float value) {
  const float shaped = shape_stick_magnitude(fabsf(value));
  return (value < 0.0f) ? -shaped : shaped;
}

/* Inverse kinematics: command -> wheel-shaft rpm for FL, FR, B (before sign). */
static void mix(float vx, float vy, float w, float out_wheel_rpm[TR_WHEEL_COUNT]) {
  float ux = vx, uy = vy;
  float mag = sqrtf(ux * ux + uy * uy);
  if (mag > 1.0f) { /* diagonal full-stick presses normalize to one unit */
    ux /= mag;
    uy /= mag;
    mag = 1.0f;
  }
  if (mag > 0.0f) {
    const float curved_mag = shape_stick_magnitude(mag);
    const float scale = curved_mag / mag;
    ux *= scale;
    uy *= scale;
  }
  if (TR_INVERT_VX)
    ux = -ux;
  if (TR_INVERT_VY)
    uy = -uy;
  float omega_ccw = shape_stick_axis(TR_INVERT_W ? w : -w); /* w > 0 means clockwise (before TR_INVERT_W) */

  float peak = 0.0f;
  for (int i = 0; i < TR_WHEEL_COUNT; i++) {
    out_wheel_rpm[i] = TR_TRANSLATE_RPM * (wheel_tx[i] * ux + wheel_ty[i] * uy) + TR_ROTATE_RPM * omega_ccw;
    if (fabsf(out_wheel_rpm[i]) > peak)
      peak = fabsf(out_wheel_rpm[i]);
  }
  if (peak > TR_MAX_WHEEL_RPM) { /* scale all together so the direction stays right */
    float k = TR_MAX_WHEEL_RPM / peak;
    for (int i = 0; i < TR_WHEEL_COUNT; i++)
      out_wheel_rpm[i] *= k;
  }
}

static void control_step(float dt, bool link_ok, float vx, float vy, float w) {
  float target_wheel_rpm[TR_WHEEL_COUNT];
  mix(link_ok ? vx : 0.0f, link_ok ? vy : 0.0f, link_ok ? w : 0.0f, target_wheel_rpm);

  for (int i = 0; i < TR_WHEEL_COUNT; i++) {
    Wheel *wh = &wheel[i];
    float target_rotor = wheel_sign[i] * target_wheel_rpm[i] * RM_GEAR_RATIO;

    wh->setpoint_rotor_rpm = link_ok ? target_rotor : 0.0f; /* no acceleration slew */

    float meas = (float)rm_get_actual_vel(wheel_bus(i), wheel_motor[i]) / RM_GEAR_RATIO; /* wheel-shaft rpm */
    float err = wh->setpoint_rotor_rpm / RM_GEAR_RATIO - meas;                       /* wheel-shaft rpm */

    float p = TR_KP * err;
    float i_new = wh->integ_a + TR_KI * err * dt;
    float d = -TR_KD * (meas - wh->prev_meas_rpm) / dt; /* on measurement: no kick when the target jumps */
    wh->prev_meas_rpm = meas;

    float u_unsat = p + i_new + d;
    float u = clampf(u_unsat, -TR_CURRENT_LIMIT_A, TR_CURRENT_LIMIT_A);
    /* Anti-windup: only keep integrating if we're not pushing further into saturation. */
    bool saturated_same_way = (u_unsat > TR_CURRENT_LIMIT_A && err > 0.0f) ||
                              (u_unsat < -TR_CURRENT_LIMIT_A && err < 0.0f);
    if (!saturated_same_way)
      wh->integ_a = clampf(i_new, -TR_CURRENT_LIMIT_A, TR_CURRENT_LIMIT_A);

    wh->current_a = u;
    rm_set_current_setpoint(wheel_bus(i), wheel_motor[i], u);

    status.target_rpm[i] = wh->setpoint_rotor_rpm / RM_GEAR_RATIO;
    status.actual_rpm[i] = meas;
    status.current_a[i] = u;
    status.temp_c[i] = rm_get_temperature(wheel_bus(i), wheel_motor[i]);
  }

  /* Queue the current-command frames and retain bus-level errors for the TFT. */
  status.can1_tx_ok = (rm_ctrl_loop(&hcan1) == HAL_OK) ? 1U : 0U;
  RM_CAN_Status can_status;
  rm_can_get_status(&hcan1, &can_status);
  status.can1_init_ok = can_status.init_ok;
  status.can1_tx_failures = can_status.tx_failures;
#if TR_BACK_ON_CAN2
  status.can2_tx_ok = (rm_ctrl_loop(&hcan2) == HAL_OK) ? 1U : 0U;
  rm_can_get_status(&hcan2, &can_status);
  status.can2_init_ok = can_status.init_ok;
  status.can2_tx_failures = can_status.tx_failures;
#else
  status.can2_tx_ok = 0U;
  status.can2_init_ok = 0U;
  status.can2_tx_failures = 0U;
#endif
}

void TRDrive_Update(void) {
  uint32_t now = HAL_GetTick();
  if (now == last_ctrl_tick)
    return; /* run the control loop once per millisecond */

  process_rx_lines(); /* parse queued lines outside the UART ISR */
  now = HAL_GetTick(); /* include queue processing in the elapsed control interval */
  const float heading_dt = (float)(now - last_ctrl_tick) / 1000.0f;
  float dt = heading_dt;
  if (dt > 0.05f) dt = 0.05f; /* after a long stall, don't take a huge step */
  last_ctrl_tick = now;

  /* Command state is updated only by process_rx_lines() in this main loop. */
  int16_t mx = cmd_mx, my = cmd_my, mr = cmd_rot;
  int8_t mech = cmd_mech;
  uint32_t t_m = last_m_tick, t_r = last_r_tick, t_g = last_g_tick, last = last_packet_tick;
  bool s_m = m_seen, s_r = r_seen, s_g = g_seen, seen = packet_seen;

  /* Each command expires on its own: a stale one counts as released. */
  if (!(s_m && (now - t_m) <= TR_LINK_TIMEOUT_MS)) {
    mx = 0;
    my = 0;
    if (s_m) {
      reset_move_average();
      m_seen = false;
    }
  }
  if (!(s_r && (now - t_r) <= TR_LINK_TIMEOUT_MS)) {
    mr = 0;
    if (s_r) {
      reset_rotation_average();
      r_seen = false;
    }
  }
  if (!(s_g && (now - t_g) <= TR_LINK_TIMEOUT_MS)) mech = 0;
  bool link_ok = seen && ((now - last) <= TR_LINK_TIMEOUT_MS);
  int8_t x = (int8_t)((mx > 0) - (mx < 0)), y = (int8_t)((my > 0) - (my < 0)), w = (int8_t)((mr > 0) - (mr < 0)), a = mech;
  float fx = (float)mx / 100.0f, fy = (float)my / 100.0f, fw = (float)mr / 100.0f;
  status.can1_ids = rm_get_feedback_mask(&hcan1, TR_CAN_FEEDBACK_TIMEOUT_MS);
#if TR_BACK_ON_CAN2
  status.can2_ids = rm_get_feedback_mask(&hcan2, TR_CAN_FEEDBACK_TIMEOUT_MS);
#else
  status.can2_ids = 0U;
#endif
  /* Heading must be re-zeroed after feedback loss or a long loop stall. */
#if TR_BACK_ON_CAN2
  const bool heading_feedback = ((status.can1_ids & 0x03U) == 0x03U) &&
                                ((status.can2_ids & 0x04U) != 0U);
#else
  const bool heading_feedback = (status.can1_ids & 0x07U) == 0x07U;
#endif
  float heading_wheel_rpm[TR_WHEEL_COUNT];
  bool wheels_stopped = true;
  for (int i = 0; i < TR_WHEEL_COUNT; ++i) {
    heading_wheel_rpm[i] = wheel_sign[i] * (float)rm_get_actual_vel(wheel_bus(i), wheel_motor[i]) / RM_GEAR_RATIO;
    if (fabsf(heading_wheel_rpm[i]) > 5.0f) wheels_stopped = false;
  }
  tr_heading_step(&heading, heading_feedback, heading_wheel_rpm[0], heading_wheel_rpm[1],
                  heading_wheel_rpm[2], heading_dt);
  const bool zeroing_heading = heading_zero_requested;
  if (heading_zero_requested) {
    if (turn.state == TR_TURN_RUN) {
      turn_cancel_requested = true; /* never reset reference during a turn */
    } else if (heading_feedback && heading_dt <= 0.1f && x == 0 && y == 0 && w == 0 && wheels_stopped) {
      heading.degrees = 0.0f;
      heading.valid = true;
    }
    heading_zero_requested = false;
  }
  const bool heading_command_fresh = heading_command_seen &&
      ((uint32_t)(now - last_heading_tick) <= TR_LINK_TIMEOUT_MS);
  if (heading_requested && (!heading_command_fresh || !link_ok)) heading.valid = false;
  status.heading_requested = heading_requested;
  status.heading_valid = heading.valid && heading_feedback && heading_command_fresh;
  status.heading_deg = (int16_t)heading.degrees;
  const bool mode_transition = heading_transition_pending;
  if (heading_transition_pending) {
    if (x == 0 && y == 0 && w == 0) heading_transition_pending = false;
    else fx = fy = fw = 0.0f; /* require neutral before a mode change drives */
  }
  if (heading_requested) {
    if (status.heading_valid && link_ok) {
      tr_heading_transform(heading.degrees, &fx, &fy);
    } else {
      fx = fy = fw = 0.0f; /* never silently switch to robot-relative motion */
    }
  }

  /* A turn is accepted only from fresh, neutral controls and stopped wheels.
   * Y0 is a release/heartbeat, not an abort; YX explicitly cancels. */
  const bool controls_fresh = s_m && s_r && (now - t_m) <= TR_LINK_TIMEOUT_MS &&
                              (now - t_r) <= TR_LINK_TIMEOUT_MS;
  const bool turn_fresh = turn_seen && (now - last_turn_tick) <= TR_LINK_TIMEOUT_MS;
  const bool manual = (x != 0 || y != 0 || w != 0);
  const bool turn_safe = link_ok && status.heading_valid && controls_fresh && turn_fresh &&
                         !manual && !mode_transition && !turn_cancel_requested && !zeroing_heading;
  if (turn_request != RDC_MESSAGE_NONE) {
    if (turn.state != TR_TURN_RUN) {
      const float target = turn_request == RDC_MESSAGE_TURN_LEFT ? -90.0f :
                           (turn_request == RDC_MESSAGE_TURN_RIGHT ? 90.0f : 180.0f);
      tr_turn_start(&turn, target, heading.degrees, now, turn_safe && wheels_stopped);
    }
    turn_request = RDC_MESSAGE_NONE;
  }
  const bool was_turning = turn.state == TR_TURN_RUN;
  if (was_turning) {
    const float fraction = tr_turn_step(&turn, now, heading.degrees, turn_safe);
    fx = fy = 0.0f;
    /* Map heading-positive rotation through the configured mixer. */
    fw = fraction * TR_HEADING_SIGN * (TR_INVERT_W ? 1.0f : -1.0f);
    if (turn.state != TR_TURN_RUN) {
      fw = 0.0f;
      for (int i = 0; i < TR_WHEEL_COUNT; ++i) wheel[i].integ_a = 0.0f;
    }
  }
  turn_cancel_requested = false;
  status.turn_state = turn.state;

  status.link_ok = link_ok;
  status.rx_bytes = dbg_rx_bytes;
  status.pkt_ok = dbg_pkt_ok;
  status.pkt_bad = dbg_pkt_bad;
  status.uart_err = dbg_uart_err;
  status.vx = link_ok ? x : 0;
  status.vy = link_ok ? y : 0;
  status.w = link_ok ? w : 0;
  status.a = link_ok ? a : 0;
  status.move_x_pct = link_ok ? mx : 0;
  status.move_y_pct = link_ok ? my : 0;
  status.rot_pct = link_ok ? mr : 0;

  control_step(dt, link_ok, fx, fy, fw);

  TRArm_Update(status.a); /* GC/GO/GS; link lost or no GO/GC => 0 => the arm just holds its position */
  status.arm_us = TRArm_GetPulseUs();

  /* Send at most one ACK per control tick so UART TX does not stall a burst of motor updates. */
  if (pending_ack_count > 0U) {
    --pending_ack_count;
    send_ack();
  }
}

void TRDrive_GetStatus(TRDrive_Status *out) {
  if (out)
    *out = status;
}
